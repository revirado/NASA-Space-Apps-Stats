export function getIso2(country: string): string | null {
  return COUNTRY_ISO2[country] ?? null;
}

/** Bandera emoji a partir de ISO2; null → globo terráqueo. */
export function flagEmoji(iso2: string | null): string {
  if (!iso2 || iso2.length !== 2) return '🌐';
  return String.fromCodePoint(
    ...iso2.toUpperCase().split('').map((c) => 0x1f1e6 + c.charCodeAt(0) - 65)
  );
}
